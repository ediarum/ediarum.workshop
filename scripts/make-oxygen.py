#!/usr/bin/env python3
"""Build oxygen/: a frameworks folder with ediarum.BASE.edit plus workshop.xpr.

    oxygen/workshop.xpr          the project file (frameworks directory = its folder)
    oxygen/ediarum.BASE.edit/    the texts framework: Author view, toolbar, person/place/org tagging

The workshop project (avhr, edition humboldt digital) is app-led: its registers are kept and
edited in the Index app, not in XML. oXygen is only used for the texts, so only
ediarum.BASE.edit is shipped. Its rules cover the letters (`telota:doctype="letter avhr"`
matches `letter*`; scripts/make-dataset.py sets it), and its tagging actions write
`persName/@key` etc., the edition's own reference style. There is no register framework
(ediarum.REGISTER.edit): the registers are edited in the Index app.

BASE takes every server URL from oXygen editor variables. workshop.xpr defines them for the
local stack, keys included: the lookups read ediarum.index's `entries/options?format=ul`, which
lists only entries with a `source_id`; entries created in the Index app get theirs from
ediarum.id at once, so they show up in the lookup right away.

One change to the framework: "link to document" actions browse from the WebDAV project root,
which ediarum.webdav maps to the repository's `data/` folder (`…/<slug>/data` is a 404 there).

    scripts/make-oxygen.py --base DIR [--env workshop.env]

--base takes a checkout or an unpacked release of ediarum.BASE.edit (with its ediarum.jar);
scripts/prepare.sh passes the one named in sources.env (BASE_EDIT_SOURCE).
"""

import argparse
import re
import shutil
import sys
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent.parent

BASE_DIR, BASE_FRAMEWORK = "ediarum.BASE.edit", "ediarum.BASE.framework"

# register lists no service provides: the proxy answers an empty list (proxy/nginx.conf)
UNAVAILABLE = "/oxygen-unavailable?list="


def read_env(path: Path) -> dict[str, str]:
    env = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip()
    return env


def variables(env: dict[str, str]) -> dict[str, str]:
    """Editor variable → value. Register URLs are concatenated by the framework as
    ${ediarum_project_domain}${ediarum_projects_directory}${ediarum_project_name}<variable>,
    i.e. http://localhost:1769 + /api/index/ + avhr + /entries/options?…"""
    base = f"http://localhost:{env['PORT']}"
    project = env["PROJECT"]

    def entries(entry_type: str) -> str:
        return f"/entries/options?entry_type={entry_type}&format=ul&key={env['INDEX_OXYGEN_KEY']}"

    new_id = f"{base}/api/id/{project}/new-id?format=xml&key={env['ID_OXYGEN_KEY']}&_=${{timeStamp}}"
    return {
        "ediarum_project_domain": base,
        "ediarum_projects_directory": "/api/index/",
        "ediarum_project_name": project,
        "ediarum_projects_directory_webdav": "/webdav/connection/",
        "ediarum_website_base": base,
        "ediarum_website_homepage": base,
        "ediarum_manual_url": "https://www.ediarum.org/docs/",
        "ediarum_index_person": entries("person"),
        "ediarum_index_place": entries("place"),
        "ediarum_index_org": entries("organisation"),
        # avhr has no works, keywords, … in the index
        "ediarum_index_bibl": UNAVAILABLE + "works",
        "ediarum_index_keyword": UNAVAILABLE + "keywords",
        "ediarum_index_letters": UNAVAILABLE + "letters",
        "ediarum_index_comments": UNAVAILABLE + "comments",
        "ediarum_index_item": UNAVAILABLE + "items",
        "ediarum_index_bibl_zotero": UNAVAILABLE + "zotero",
        "ediarum_getGeoname": UNAVAILABLE + "geonames",
        # an xml:id from ediarum.id wherever a template or action asks for one
        "ediarum_id": f"${{xpath_eval(doc('{new_id}')//new-id/text())}}",
    }


XPR = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/make-oxygen.py: the ediarum workshop's oXygen project. -->
<project>
    <meta>
        <filters directoryPatterns="" filePatterns="" positiveFilePatterns="" showHiddenFiles="false"/>
        <options>
            <serialized xml:space="preserve">
                <serializableOrderedMap>
                    <entry>
                        <String>document.types</String>
                        <documentTypeDescriptor-array/>
                    </entry>
                    <entry>
                        <String>frameworks.directory.url.with.editor.variables</String>
                        <String>${{pdu}}</String>
                    </entry>
                    <entry>
                        <String>key.custom.editor.variables.option.pane</String>
                        <Boolean>true</Boolean>
                    </entry>
                    <entry>
                        <String>key.editor.document.type.association.option.pane</String>
                        <Boolean>true</Boolean>
                    </entry>
                    <entry>
                        <String>key.editor.document.type.custom.locations.option.pane</String>
                        <Boolean>true</Boolean>
                    </entry>
                    <entry>
                        <String>key.trusted.hosts.option.pane</String>
                        <Boolean>true</Boolean>
                    </entry>
                    <entry>
                        <String>trusted.hosts</String>
                        <String-array>
                            <String>localhost:{port}</String>
                        </String-array>
                    </entry>
                    <entry>
                        <String>use.custom.frameworks.directory.url</String>
                        <Boolean>true</Boolean>
                    </entry>
                    <entry>
                        <String>user.defined.editor.variables</String>
                        <userEditorVariable-array>
{variables}                        </userEditorVariable-array>
                    </entry>
                    <entry>
                        <String>xpath.proxy.ns.mappings</String>
                        <String-array>
                            <String>tei</String>
                            <String>http://www.tei-c.org/ns/1.0</String>
                            <String>telota</String>
                            <String>http://www.telota.de</String>
                        </String-array>
                    </entry>
                </serializableOrderedMap>
            </serialized>
        </options>
    </meta>
    <projectTree name="workshop.xpr"/>
</project>
"""

VARIABLE = """                            <userEditorVariable>
                                <field name="name">
                                    <String>${{{name}}}</String>
                                </field>
                                <field name="value">
                                    <String>{value}</String>
                                </field>
                                <field name="shortDescription">
                                    <String>ediarum.workshop</String>
                                </field>
                            </userEditorVariable>
"""


def workshop_xpr(env: dict[str, str]) -> str:
    rows = "".join(VARIABLE.format(name=n, value=escape(v)) for n, v in variables(env).items())
    return XPR.format(port=env["PORT"], variables=rows)


def patch_webdav_root(framework: str) -> str:
    "ediarum.webdav serves a project's data/ folder as /webdav/connection/<slug>/."
    return re.sub(
        r"(\$\{ediarum_projects_directory_webdav\}\$\{ediarum_project_name\})/data/?(?=</String>)",
        r"\1",
        framework,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--base", type=Path, required=True, help="ediarum.BASE.edit checkout or release")
    parser.add_argument("--env", type=Path, default=HERE / "workshop.env")
    parser.add_argument("--out", type=Path, default=HERE / "oxygen")
    args = parser.parse_args()

    base: Path = args.base.resolve()
    if not (base / BASE_FRAMEWORK).is_file():
        sys.exit(f"{base}: no {BASE_FRAMEWORK} — not an ediarum.BASE.edit checkout?")
    if not (base / "ediarum.jar").is_file():
        sys.exit(f"{base}: no ediarum.jar — take it from a release of the framework (or of ediarum.JAR)")
    env = read_env(args.env)

    out: Path = args.out
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    ignore = shutil.ignore_patterns(".git", ".gitignore", ".gitlab-ci.yml", ".workshop-source", "*.xpr")
    shutil.copytree(base, out / BASE_DIR, ignore=ignore)
    fw = out / BASE_DIR / BASE_FRAMEWORK
    fw.write_text(patch_webdav_root(fw.read_text(encoding="utf-8")), encoding="utf-8")

    (out / "workshop.xpr").write_text(workshop_xpr(env), encoding="utf-8")
    print(f"oxygen: {out.relative_to(HERE)}/workshop.xpr (open this project file in oXygen)")


if __name__ == "__main__":
    main()
